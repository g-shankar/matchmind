def text_width(text: str, scale: int = 1) -> int:
    return len(text) * 6 * scale


def draw_text(img, text: str, x: int, y: int, colour: tuple[int, int, int], scale: int = 1) -> None:
    """Burn `text` (upper-cased; unknown characters become spaces) into an HxWx3 uint8 array."""
    h, w = img.shape[:2]
    cx = x
    for ch in text.upper():
        rows = _GLYPHS.get(ch, _GLYPHS[" "])
        for r, line in enumerate(rows):
            for c, bit in enumerate(line):
                if bit != "#":
                    continue
                y0, x0 = y + r * scale, cx + c * scale
                if y0 >= 0 and x0 >= 0 and y0 + scale <= h and x0 + scale <= w:
                    img[y0 : y0 + scale, x0 : x0 + scale] = colour
        cx += 6 * scale
