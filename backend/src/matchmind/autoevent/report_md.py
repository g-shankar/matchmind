"""Markdown report for a benchmark run (what `matchmind-autoevent benchmark --md` writes)."""

from __future__ import annotations

from .benchmark import BenchmarkResult, SplitResult
from .score import KINDS, ClassRow


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _ci(ci: tuple[float, float] | None) -> str:
    return f"{100 * ci[0]:.1f}-{100 * ci[1]:.1f}%" if ci else "n/a"


def class_table(rows: list[ClassRow]) -> list[str]:
    out = [
        "| Class | Support (true) | Detected | Matched | Precision (95% CI) | Recall (95% CI) | F1 |",
        "|---|---:|---:|---:|---|---|---:|",
    ]
    for r in rows:
        out.append(
            f"| {r.kind} | {r.support} | {r.detected} | {r.matched} |"
            f" {_pct(r.precision)} ({_ci(r.precision_ci)}) | {_pct(r.recall)} ({_ci(r.recall_ci)}) |"
            f" {r.f1:.3f} |"
        )
    return out


def confusion_table(split: SplitResult) -> list[str]:
    c = split.confusion
    out = [
        "| true \\ detected | " + " | ".join(c.columns) + " | total |",
        "|---|" + "---:|" * (len(c.columns) + 1),
    ]
    for name, row in zip(c.rows, c.counts, strict=True):
        out.append(f"| **{name}** | " + " | ".join(str(v) for v in row) + f" | {sum(row)} |")
    return out


def _split(title: str, s: SplitResult) -> list[str]:
    mae = f"{s.speed_mae_kmh:.2f} km/h" if s.speed_mae_kmh is not None else "n/a"
    ci = f"{s.speed_mae_ci_kmh[0]:.2f}-{s.speed_mae_ci_kmh[1]:.2f}" if s.speed_mae_ci_kmh else "n/a"
    out = [
        f"### {title}",
        "",
        f"Matches: {', '.join(s.matches)} (seeds {', '.join(str(x) for x in s.seeds)}); {s.frames:,} frames.",
        "",
        *class_table([*s.classes, s.pressure]),
        "",
        f"Kick-speed MAE (matched passes and shots): **{mae}** (95% bootstrap CI {ci} km/h,"
        f" n = {s.speed_samples}). Right receiver on matched complete passes:"
        f" {_pct(s.receiver_accuracy) if s.receiver_accuracy is not None else 'n/a'}.",
        "",
        "Confusion matrix (rows: true kind or *spurious*; columns: detected kind or *missed*).",
        "Pressure is scored separately (it rides on a kick, so it is not a kind of its own here).",
        "",
        *confusion_table(s),
        "",
        f"Baseline: {s.baseline.name}.",
        "",
        *class_table([r for r in s.baseline.classes if r.kind in ("pass", "tackle", "pressure")]),
        "",
    ]
    return out


def to_markdown(r: BenchmarkResult) -> str:
    lines = [
        f"# {r.name}: results",
        "",
        f"> **{r.label}.** {r.caveat}",
        "",
        "Generated by `matchmind-autoevent benchmark`. Every number below comes from that run.",
        "",
        "## Split design",
        "",
        r.tuning_note,
        "",
        f"Thresholds set on the tuning split: {', '.join(f'`{t}`' for t in r.tuned_thresholds)}.",
        "",
        *_split("Held-out split (the headline)", r.held_out),
        *_split("Tuning split (for reference; optimistic by construction)", r.tuning),
        "## Robustness sweep",
        "",
        f"Held-out matches {', '.join(r.robustness_matches)}, with extra noise and dropouts added to the"
        " feed before detection. F1 per class:",
        "",
        "| Setting | " + " | ".join(KINDS) + " | pressure | kick-speed MAE |",
        "|---|" + "---:|" * (len(KINDS) + 2),
    ]
    for row in r.robustness:
        f1s = " | ".join(f"{c.f1:.3f}" for c in row.classes)
        mae = f"{row.speed_mae_kmh:.2f} km/h" if row.speed_mae_kmh is not None else "n/a"
        lines.append(f"| {row.name} | {f1s} | {row.pressure.f1:.3f} | {mae} |")
    lines.append("")
    if r.pixel is not None:
        p = r.pixel
        lines += [
            "## Pixel path",
            "",
            f"> **{p.label}.**",
            "",
            f"Held-out matches {', '.join(p.matches)}, the first {p.window_s:g} s of each, rendered at"
            f" {p.width_px} x {p.height_px} px ({p.px_per_m:g} px per metre), {p.frames:,} frames. Vision"
            f" step: {p.seconds_per_match:g} s per match window. Recovered player positions: median error"
            f" {p.player_error_m} m (95th percentile {p.player_error_p95_m} m); ball: median"
            f" {p.ball_error_m} m, recovered in {p.ball_found_pct:.1f}% of frames where it was tracked.",
            "",
            "Coordinate path on the same frames:",
            "",
            *class_table([*p.coordinate, p.coordinate_pressure]),
            "",
            "Pixel path (same detector, positions recovered from the rendered frames):",
            "",
            *class_table([*p.pixels, p.pixels_pressure]),
            "",
            f"Kick-speed MAE: coordinate {p.speed_mae_kmh_coordinate} km/h, pixels"
            f" {p.speed_mae_kmh_pixels} km/h.",
            "",
        ]
    if r.failures:
        lines += ["## Failure examples (held-out)", ""]
        for f in r.failures:
            img = f" ![{f.what}](images/{f.image})" if f.image else ""
            lines.append(
                f"- `{f.what}`: {f.match_id} at {f.match_clock} (true {f.truth_kind or 'nothing'},"
                f" detected {f.detected_kind or 'nothing'}).{img}"
            )
        lines.append("")
    lines.append(f"Runtime: {r.runtime_s:g} s.")
    return "\n".join(lines) + "\n"
