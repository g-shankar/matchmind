"""Agent manifests for the five studio crew agents, generated from the code.

The system prompts, JSON schemas, model settings and guardrail numbers are
read from the crew modules themselves, so the manifests in `foundry/agents/`
can never say something the running crew does not do. A test fails when the
committed files differ from a fresh `matchmind-foundry export`.

Each model-backed manifest lists exactly the fields a Microsoft Foundry
Agent Service prompt agent takes (name, model deployment, instructions,
response format, tools). PitchPulse itself calls the model deployment
directly through `crew/llm.py`; nothing here registers agents in Foundry.
"""

from __future__ import annotations

import inspect
from pathlib import Path
from types import ModuleType
from typing import Any

import yaml
from pydantic import BaseModel

from matchmind.crew import analyst, commentator, crew, fact_checker, llm, producer, recap, spotter
from matchmind.crew.contracts import Explanation, FactCheck, Moment, MomentBundle, Narrative, OverlayCard
from matchmind.foundry.contracts import (
    AnalystIn,
    CommentatorIn,
    FactCheckIn,
    ProducerIn,
    RecapIn,
    SpotterIn,
    SpotterOut,
)

MANIFEST_SCHEMA = "pitchpulse.agent-manifest/v1"
HEADER = "# Generated by `matchmind-foundry export` from backend/src/matchmind/crew. Do not edit by hand.\n"


def _schema(model: type[BaseModel]) -> dict[str, Any]:
    return model.model_json_schema()


def _behaviour(module: ModuleType) -> str:
    return inspect.cleandoc(module.__doc__ or "").strip()


def _model_step(
    step: str, system: str, model_in: type[BaseModel], model_out: type[BaseModel]
) -> dict[str, Any]:
    return {
        "step": step,
        "deployment": llm.DEFAULT_DEPLOYMENT,
        "deployment_setting": "AZURE_OPENAI_DEPLOYMENT",
        "api": "Azure OpenAI chat completions (Microsoft Entra ID, no key)",
        "api_version": llm.DEFAULT_API_VERSION,
        "response_format": "json_object, validated against the output schema",
        "temperature": llm.TEMPERATURE,
        "max_tokens": llm.MAX_TOKENS,
        "instructions": system.strip(),
        "input_schema": _schema(model_in),
        "output_schema": _schema(model_out),
        "agent_service": {
            "name": None,  # filled in below with the agent's name
            "model": llm.DEFAULT_DEPLOYMENT,
            "instructions": "the `instructions` above",
            "response_format": {
                "type": "json_schema",
                "json_schema": {"name": model_out.__name__, "schema": "the `output_schema` above"},
            },
            "tools": [],
        },
    }


def _guardrails(model_backed: bool) -> list[str]:
    rules = [
        "Input is typed facts from the PitchPulse stats engine only; no viewer free text reaches an agent.",
    ]
    if model_backed:
        rules += [
            f"Timeout {crew.STEP_TIMEOUT_S:g} s per model call, one repair retry on a schema mismatch, "
            "then the localised template.",
            f"Circuit breaker: {crew.BREAKER_FAILURES} failures in a row open it "
            f"for {crew.BREAKER_OPEN_S:g} s.",
            "Process-wide model budget (MATCHMIND_AI_BUDGET, MATCHMIND_AI_RATE_PER_MIN); "
            "fallback_reason 'budget' once spent.",
            "Every model text is fact-checked (strict number words); a rejected text is never shown.",
            "Paid model calls only when MATCHMIND_AI_ENABLED=true (off by default).",
        ]
    return rules


def manifests() -> list[dict[str, Any]]:
    """The five agents, in pipeline order."""
    agents: list[dict[str, Any]] = [
        {
            "name": "pitchpulse-spotter",
            "display_name": "Spotter",
            "role": "Turns each match event plus the stats engine's numbers into moments worth telling.",
            "runtime": "deterministic",
            "source": "matchmind.crew.spotter.Spotter.spot",
            "behaviour": _behaviour(spotter),
            "contract": {"input": _schema(SpotterIn), "output": _schema(SpotterOut)},
            "model_steps": [],
        },
        {
            "name": "pitchpulse-analyst",
            "display_name": "Analyst",
            "role": "Explains why a moment matters, with the evidence behind it.",
            "runtime": "model_with_template_fallback",
            "source": "matchmind.crew.analyst",
            "behaviour": _behaviour(analyst),
            "contract": {"input": _schema(Moment), "output": _schema(Explanation)},
            "model_steps": [_model_step("analyst", analyst.ANALYST_SYSTEM, AnalystIn, analyst.AnalystOut)],
        },
        {
            "name": "pitchpulse-commentator",
            "display_name": "Commentator",
            "role": "Voices one moment for one audience (persona) in one language.",
            "runtime": "model_with_template_fallback",
            "source": "matchmind.crew.commentator",
            "behaviour": _behaviour(commentator),
            "contract": {"input": _schema(MomentBundle), "output": _schema(Narrative)},
            "model_steps": [
                _model_step(
                    "commentator",
                    commentator.COMMENTATOR_SYSTEM,
                    CommentatorIn,
                    commentator.CommentatorOut,
                )
            ],
        },
        {
            "name": "pitchpulse-fact-checker",
            "display_name": "Fact-checker",
            "role": "Gates every text: each number must be a stats-engine fact; length and name rules apply.",
            "runtime": "deterministic",
            "source": "matchmind.crew.fact_checker.check",
            "behaviour": _behaviour(fact_checker),
            "contract": {"input": _schema(FactCheckIn), "output": _schema(FactCheck)},
            "model_steps": [],
        },
        {
            "name": "pitchpulse-producer",
            "display_name": "Producer",
            "role": "Times and places overlay cards per viewer, and writes the match recap.",
            "runtime": "deterministic cards; recap is model_with_template_fallback at full time",
            "source": "matchmind.crew.producer, matchmind.crew.recap",
            "behaviour": _behaviour(producer) + "\n\nRecap:\n" + _behaviour(recap),
            "contract": {"input": _schema(ProducerIn), "output": _schema(OverlayCard)},
            "model_steps": [_model_step("recap", recap.RECAP_SYSTEM, RecapIn, recap.RecapOut)],
        },
    ]
    out = []
    for agent in agents:
        model_backed = bool(agent["model_steps"])
        for step in agent["model_steps"]:
            step["agent_service"]["name"] = (
                agent["name"] if step["step"] != "recap" else f"{agent['name']}-recap"
            )
        out.append(
            {
                "schema": MANIFEST_SCHEMA,
                **{k: agent[k] for k in ("name", "display_name", "role", "runtime", "source")},
                "tools": [],
                "guardrails": _guardrails(model_backed),
                "model_steps": agent["model_steps"],
                "behaviour": agent["behaviour"],
                "contract": agent["contract"],
            }
        )
    return out


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.Node:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def to_yaml(manifest: dict[str, Any]) -> str:
    return HEADER + yaml.dump(manifest, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)


def export(out_dir: str | Path) -> list[Path]:
    """Write one `<name>.yaml` per agent; returns the paths written."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for manifest in manifests():
        path = out / f"{manifest['name'].removeprefix('pitchpulse-')}.yaml"
        path.write_text(to_yaml(manifest), encoding="utf-8")
        paths.append(path)
    return paths
